let CURRENT_LANG = localStorage.getItem("rysao_lang") || "fr";

function t(key) {
  const lang = I18N[CURRENT_LANG] || I18N.fr;
  return lang[key] || I18N.fr[key] || key;
}

function setLang(code) {
  if (!I18N[code]) return;
  CURRENT_LANG = code;
  localStorage.setItem("rysao_lang", code);
  document.documentElement.lang = code;
  if (window.applyI18n) window.applyI18n();
}

window.I18N = I18N;
window.t = t;
window.setLang = setLang;
